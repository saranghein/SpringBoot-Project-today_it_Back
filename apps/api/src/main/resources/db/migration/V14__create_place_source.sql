CREATE TABLE place_source (
    place_source_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    place_id INTEGER NOT NULL,
    provider VARCHAR NOT NULL,
    source_id VARCHAR NOT NULL,
    CONSTRAINT fk_place_source_place FOREIGN KEY (place_id)
        REFERENCES place (place_id) ON DELETE RESTRICT,
    CONSTRAINT uk_place_source_provider_source UNIQUE (provider, source_id),
    CONSTRAINT ck_place_source_provider CHECK (btrim(provider) <> ''),
    CONSTRAINT ck_place_source_source_id CHECK (btrim(source_id) <> '')
);

CREATE INDEX ix_place_source_place_id ON place_source (place_id);

COMMENT ON TABLE place_source IS '공급원 장소와 서비스 장소의 연결. 서로 다른 원천을 자동 병합하지 않음';
COMMENT ON COLUMN place_source.place_source_id IS '단일 원천 연결 식별자';
COMMENT ON COLUMN place_source.place_id IS '서비스 장소 식별자';
COMMENT ON COLUMN place_source.provider IS '공급원 코드';
COMMENT ON COLUMN place_source.source_id IS '공급원 장소 ID 원문. provider와 함께 유일';
