CREATE TABLE region (
                        region_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        si VARCHAR(20) NOT NULL,
                        gun VARCHAR(20) NOT NULL,
                        gu VARCHAR(30) NOT NULL
);

CREATE TABLE roles (
                       roles_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       name VARCHAR(20) NOT NULL,
                       accessible_entity VARCHAR(20) NOT NULL,
                       created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                       deleted_at TIMESTAMP WITH TIME ZONE,
                       CONSTRAINT uk_roles_name UNIQUE (name),
                       CONSTRAINT ck_roles_name CHECK (name IN ('ADMIN', 'USER', 'DEV'))
);

CREATE TABLE agreement (
                           agreement_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           code VARCHAR(32) NOT NULL,
                           title VARCHAR(100) NOT NULL,
                           content VARCHAR(8000) NOT NULL,
                           version VARCHAR(8) NOT NULL,
                           is_required BOOLEAN NOT NULL,
                           created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                           updated_at TIMESTAMP WITH TIME ZONE,
                           is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
                           CONSTRAINT uk_agreement_code_version UNIQUE (code, version)
);
CREATE UNIQUE INDEX uk_agreement_active_code
    ON agreement (code)
    WHERE is_deleted = FALSE;

CREATE TABLE member (
                        member_id VARCHAR(36) PRIMARY KEY,
                        preferred_region INTEGER,
                        email VARCHAR(100),
                        password VARCHAR(100),
                        provider VARCHAR(20) NOT NULL,
                        provider_user_id VARCHAR(255),
                        nickname VARCHAR(50) NOT NULL,
                        profile_image VARCHAR(2048) NOT NULL DEFAULT '/images/default-profile.png',
                        preferred_theme VARCHAR(20),
                        is_active BOOLEAN NOT NULL DEFAULT TRUE,
                        created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                        updated_at TIMESTAMP WITH TIME ZONE,
                        CONSTRAINT uk_member_email_provider UNIQUE (email, provider),
                        CONSTRAINT fk_member_preferred_region
                            FOREIGN KEY (preferred_region) REFERENCES region (region_id),
                        CONSTRAINT ck_member_provider CHECK (provider IN ('LOCAL', 'GOOGLE', 'KAKAO')),
                        CONSTRAINT ck_member_local_password CHECK (
                            (provider = 'LOCAL' AND password IS NOT NULL)
                                OR (provider <> 'LOCAL' AND password IS NULL)
                            )
);
CREATE UNIQUE INDEX uk_member_email_provider_normalized
    ON member (LOWER(BTRIM(email)), provider)
    WHERE email IS NOT NULL;
CREATE UNIQUE INDEX uk_member_nickname_normalized
    ON member (LOWER(BTRIM(nickname)));

CREATE TABLE member_roles (
                              member_role_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              member_id VARCHAR(36) NOT NULL,
                              roles_id INTEGER NOT NULL,
                              CONSTRAINT uk_member_roles UNIQUE (member_id, roles_id),
                              CONSTRAINT fk_member_roles_member
                                  FOREIGN KEY (member_id) REFERENCES member (member_id),
                              CONSTRAINT fk_member_roles_roles
                                  FOREIGN KEY (roles_id) REFERENCES roles (roles_id)
);

CREATE TABLE member_agreement (
                                  member_agreement_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  agreement_id INTEGER NOT NULL,
                                  member_id VARCHAR(36) NOT NULL,
                                  is_agreement BOOLEAN NOT NULL,
                                  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                  updated_at TIMESTAMP WITH TIME ZONE,
                                  is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
                                  CONSTRAINT uk_member_agreement UNIQUE (member_id, agreement_id),
                                  CONSTRAINT fk_member_agreement_agreement
                                      FOREIGN KEY (agreement_id) REFERENCES agreement (agreement_id),
                                  CONSTRAINT fk_member_agreement_member
                                      FOREIGN KEY (member_id) REFERENCES member (member_id)
);

