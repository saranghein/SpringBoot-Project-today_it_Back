CREATE TABLE place_job_run (
    place_job_run_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_type VARCHAR(30) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'RUNNING',
    collection_result JSONB,
    ingestion_result JSONB,
    error_code VARCHAR(30),
    started_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finished_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ck_place_job_run_type CHECK (job_type IN ('COLLECT_AND_INGEST', 'RETRY_FAILED')),
    CONSTRAINT ck_place_job_run_status CHECK (status IN ('RUNNING', 'SUCCESS', 'FAILED')),
    CONSTRAINT ck_place_job_run_finished CHECK (
        (status = 'RUNNING' AND finished_at IS NULL AND error_code IS NULL)
        OR (status = 'SUCCESS' AND finished_at IS NOT NULL AND error_code IS NULL)
        OR (status = 'FAILED' AND finished_at IS NOT NULL AND error_code IS NOT NULL)
    )
);

COMMENT ON TABLE place_job_run IS '장소 정기 실행 이력';
COMMENT ON COLUMN place_job_run.job_type IS '작업 종류';
COMMENT ON COLUMN place_job_run.status IS '실행 상태';
COMMENT ON COLUMN place_job_run.collection_result IS '수집 집계';
COMMENT ON COLUMN place_job_run.ingestion_result IS '적재 집계';
COMMENT ON COLUMN place_job_run.error_code IS '실패 분류';
