CREATE TABLE external_place_raw (
    external_place_raw_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider VARCHAR NOT NULL,
    source_id VARCHAR NOT NULL,
    payload JSONB,
    status VARCHAR NOT NULL DEFAULT 'PENDING',
    error_code VARCHAR,
    collected_at TIMESTAMP WITH TIME ZONE,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_external_place_raw_provider_source UNIQUE (provider, source_id),
    CONSTRAINT ck_external_place_raw_provider CHECK (btrim(provider) <> ''),
    CONSTRAINT ck_external_place_raw_source_id CHECK (btrim(source_id) <> ''),
    CONSTRAINT ck_external_place_raw_status CHECK (status IN ('PENDING', 'SUCCESS', 'FAILED')),
    CONSTRAINT ck_external_place_raw_success CHECK (
        status <> 'SUCCESS' OR (payload IS NOT NULL AND collected_at IS NOT NULL AND error_code IS NULL)
    )
);

COMMENT ON TABLE external_place_raw IS '외부 장소 원본. 정제 및 서비스 장소 반영 여부와 무관한 수집 상태';
COMMENT ON COLUMN external_place_raw.external_place_raw_id IS '단일 원본 식별자';
COMMENT ON COLUMN external_place_raw.provider IS '공급원 코드';
COMMENT ON COLUMN external_place_raw.source_id IS '공급원의 장소 식별자. 지역 코드가 아님';
COMMENT ON COLUMN external_place_raw.payload IS '목록, 공통, 소개, 이미지 원본 JSON. 첫 실패는 재수집용 목록만 보존';
COMMENT ON COLUMN external_place_raw.status IS '최근 수집 시도 상태: PENDING, SUCCESS, FAILED';
COMMENT ON COLUMN external_place_raw.error_code IS '비밀정보를 포함하지 않는 최근 실패 분류';
COMMENT ON COLUMN external_place_raw.collected_at IS '모든 필수 구성 요소의 최근 성공 수집 시각. 첫 성공 전 NULL';
COMMENT ON COLUMN external_place_raw.updated_at IS 'DB에서 기록하는 최근 행 생성 또는 변경 시각';
