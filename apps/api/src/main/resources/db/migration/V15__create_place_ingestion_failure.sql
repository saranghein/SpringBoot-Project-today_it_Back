CREATE TABLE place_ingestion_failure (
    place_ingestion_failure_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_place_raw_id BIGINT NOT NULL,
    error_code VARCHAR(30) NOT NULL,
    failure_count INTEGER NOT NULL DEFAULT 1,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_failed_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_place_ingestion_failure_raw UNIQUE (external_place_raw_id),
    CONSTRAINT fk_place_ingestion_failure_raw FOREIGN KEY (external_place_raw_id)
        REFERENCES external_place_raw (external_place_raw_id) ON DELETE CASCADE,
    CONSTRAINT ck_place_ingestion_failure_count CHECK (failure_count > 0),
    CONSTRAINT ck_place_ingestion_failure_code CHECK (error_code IN ('DATA_INTEGRITY', 'TRANSACTION', 'DATA_ACCESS'))
);

COMMENT ON TABLE place_ingestion_failure IS '장소 적재 실패';
COMMENT ON COLUMN place_ingestion_failure.external_place_raw_id IS '원본 식별자';
COMMENT ON COLUMN place_ingestion_failure.error_code IS '최근 오류 코드';
COMMENT ON COLUMN place_ingestion_failure.failure_count IS '누적 실패 횟수';
